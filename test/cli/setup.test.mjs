const RULE_FILES = ["EXAMPLES.md", "RULES.md"];
const PRE_COMMIT_PATH = ".husky/pre-commit";
const PRE_PUSH_PATH = ".husky/pre-push";
const CHECK_COMMIT_LINE = "node_modules/.bin/style-guide check-commit";
const BIOME_LINE =
  "node_modules/.bin/biome check --staged --no-errors-on-unmatched";
const CHECK_PUSH_LINE = "node_modules/.bin/style-guide check-push";
const COMPLETE_MANIFEST = {
  scripts: { prepare: "husky" },
  devDependencies: { "@pleand-inc/style-guide": "1.2.3", husky: "9.1.7" },
};

function manifestText(overrides) {
  return JSON.stringify({ ...COMPLETE_MANIFEST, ...overrides });
}

function contentOf(path) {
  const file = ownedFiles(RULE_FILES).find((owned) => owned.path === path);
  assert.ok(file, `${path} is not an owned file`);
  return file.content;
}

/** The files of a repository that `init` has set up and that needs no manual step. */
function completeRepositoryFiles() {
  return new Map([
    ...ownedFiles(RULE_FILES).map(({ path, content }) => [path, content]),
    [PRE_COMMIT_PATH, `${CHECK_COMMIT_LINE}\n${BIOME_LINE}\n`],
    [PRE_PUSH_PATH, `${CHECK_PUSH_LINE}\n`],
    ["package.json", manifestText({})],
    ["biome.json", '{ "extends": ["@pleand-inc/style-guide/biome"] }'],
  ]);
}

function usesLines(workflowText) {
  return workflowText
    .split("\n")
    .filter((line) => line.includes("uses:"))
    .map((line) => line.trim().replace(/^- /, ""));
}

const pullRequest = pullRequestWorkflowFile();
const push = pushWorkflowFile();

describe("both generated workflows", () => {
  for (const [name, workflow] of [
    ["pull request", pullRequest],
    ["push", push],
  ]) {
    it(`${name}: starts with a comment that says it is generated and not edited by hand`, () => {
      const firstLine = workflow.split("\n")[0];
      assert.match(
        firstLine,
        /^# Generated by `style-guide init`\. Do not edit by hand/,
      );
    });

    it(`${name}: grants nothing at the top level and limits every job to five minutes`, () => {
      assert.match(workflow, /^permissions: \{\}$/m);
      const jobCount = workflow.match(/^ {4}runs-on: ubuntu-latest$/gm).length;
      assert.equal(
        workflow.match(/^ {4}timeout-minutes: 5$/gm).length,
        jobCount,
      );
      assert.equal(workflow.match(/^ {4}permissions:$/gm).length, jobCount);
    });

    it(`${name}: pins the actions to the commits .github/workflows/test.yml uses`, () => {
      const testWorkflow = readFileSync(
        join(REPOSITORY_ROOT, ".github", "workflows", "test.yml"),
        "utf8",
      );
      const pinned = usesLines(testWorkflow);
      assert.equal(pinned.length, 2);
      assert.deepEqual([...new Set(usesLines(workflow))], pinned);
    });

    it(`${name}: runs on the current LTS of Node and skips the Biome peer dependency`, () => {
      const jobCount = workflow.match(/^ {4}runs-on: ubuntu-latest$/gm).length;
      assert.equal(
        workflow.match(/^ {10}node-version: lts\/\*$/gm).length,
        jobCount,
      );
      assert.equal(
        workflow.match(/^ {10}NPM_CONFIG_LEGACY_PEER_DEPS: "true"$/gm).length,
        jobCount,
      );
    });

    it(`${name}: never installs the repository's own dependencies and names no version`, () => {
      assert.doesNotMatch(workflow, /npm (ci|install)|pnpm|yarn/);
      assert.doesNotMatch(workflow, /@pleand-inc\/style-guide@\d/);
    });

    it(`${name}: ends with one newline and has no tab or trailing space`, () => {
      assert.match(workflow, /[^\n]\n$/);
      assert.doesNotMatch(workflow, /\t| \n/);
    });
  }
});

describe("the generated pull request workflow", () => {
  it("runs on the four pull request activity types", () => {
    assert.match(
      pullRequest,
      /^on:\n {2}pull_request:\n {4}types: \[opened, reopened, synchronize, edited\]\n/m,
    );
    assert.doesNotMatch(pullRequest, /^ {2}push:/m);
  });

  it("has the pairing job and the setup job, each with read-only contents", () => {
    assert.match(
      pullRequest,
      /^ {2}pull-request-pairing:\n {4}name: pull request pairing$/m,
    );
    assert.match(
      pullRequest,
      /^ {2}style-guide-setup:\n {4}name: style guide setup$/m,
    );
    assert.equal(pullRequest.match(/^ {6}contents: read$/gm).length, 2);
    assert.doesNotMatch(pullRequest, /write|pull-requests:/);
  });

  it("passes the base and head through the environment, not through the script", () => {
    assert.match(pullRequest, /^ {10}BASE_REF: \$\{\{ github\.base_ref \}\}$/m);
    assert.match(pullRequest, /^ {10}HEAD_REF: \$\{\{ github\.head_ref \}\}$/m);
    assert.match(pullRequest, /-- style-guide check-pull-request$/m);
    assert.match(pullRequest, /-- style-guide check$/m);
    const runLines = pullRequest
      .split("\n")
      .filter((line) => line.includes("npm exec") || line.includes("spec="));
    assert.equal(
      runLines.some((line) => line.includes("${{")),
      false,
    );
  });
});

describe("the generated push workflow", () => {
  it("runs on pushes to master and develop only", () => {
    assert.match(
      push,
      /^on:\n {2}push:\n {4}branches:\n {6}- master\n {6}- develop\n\n/m,
    );
    assert.doesNotMatch(push, /pull_request:/);
  });

  it("has the landed commit job, which may read contents and pull requests", () => {
    assert.match(push, /^ {2}landed-commit:\n {4}name: landed commit$/m);
    assert.match(
      push,
      /^ {4}permissions:\n {6}contents: read\n {6}pull-requests: read\n {4}steps:$/m,
    );
    assert.match(push, /^ {10}GITHUB_TOKEN: \$\{\{ github\.token \}\}$/m);
    assert.match(push, /-- style-guide check-landed-commit$/m);
    assert.doesNotMatch(push, /write/);
  });
});

