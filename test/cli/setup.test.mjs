describe("the generated skill", () => {
  const skill = skillFile(RULE_FILES);

  it("starts with front matter that names the skill and says when to use it", () => {
    const lines = skill.split("\n");
    assert.deepEqual(lines.slice(0, 2), ["---", "name: style-guide"]);
    assert.match(
      lines[2],
      /^description: Use when writing, editing or reviewing code in this repository/,
    );
    assert.match(lines[2], /branch|merging/);
    assert.doesNotMatch(lines[2].slice("description: ".length), /: /);
    assert.equal(lines[3], "---");
  });

  it("says right after the front matter that it is generated and not edited by hand", () => {
    assert.match(
      skill.split("\n")[5],
      /^<!-- Generated by `style-guide init`\. Do not edit by hand.* -->$/,
    );
  });

  it("lists every rule file it is given under the installed package, in the order given", () => {
    const listed = skill
      .split("\n")
      .filter((line) =>
        line.startsWith("- `node_modules/@pleand-inc/style-guide/rules/"),
      );
    assert.deepEqual(listed, [
      "- `node_modules/@pleand-inc/style-guide/rules/EXAMPLES.md`",
      "- `node_modules/@pleand-inc/style-guide/rules/RULES.md`",
    ]);
    const nested = skillFile(["RULES.md", "typescript/TYPES.md"]);
    assert.match(
      nested,
      /^- `node_modules\/@pleand-inc\/style-guide\/rules\/typescript\/TYPES\.md`$/m,
    );
    assert.doesNotMatch(nested, /EXAMPLES\.md/);
  });

  it("points at the branch flow, the merge command, and says rules are not edited here", () => {
    assert.match(
      skill,
      /`node_modules\/@pleand-inc\/style-guide\/process\/branch-flow\.md`/,
    );
    assert.match(skill, /`node_modules\/\.bin\/style-guide merge <번호>`/);
    assert.match(skill, /규칙은 이 저장소에서 고치지 않습니다\./);
  });
});

