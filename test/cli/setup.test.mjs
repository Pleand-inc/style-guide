describe("missingHookLines", () => {
  const preCommit = HOOKS[0].requiredLines;

  it("is empty when a line holds each marker, however the command is reached", () => {
    assert.deepEqual(
      missingHookLines(preCommit, `${CHECK_COMMIT_LINE}\n${BIOME_LINE}\n`),
      [],
    );
    assert.deepEqual(
      missingHookLines(
        preCommit,
        "pnpm exec style-guide check-commit\r\nnpx biome check --staged\r\n",
      ),
      [],
    );
    assert.deepEqual(
      missingHookLines(
        preCommit,
        `npm test\n  ${BIOME_LINE} && ${CHECK_COMMIT_LINE}`,
      ),
      [],
    );
  });

  it("returns the exact line to add for each marker no line holds", () => {
    assert.deepEqual(missingHookLines(preCommit, "npm test\n"), [
      CHECK_COMMIT_LINE,
      BIOME_LINE,
    ]);
    assert.deepEqual(missingHookLines(preCommit, `${CHECK_COMMIT_LINE}\n`), [
      BIOME_LINE,
    ]);
    assert.deepEqual(missingHookLines(preCommit, `${BIOME_LINE}\n`), [
      CHECK_COMMIT_LINE,
    ]);
    assert.deepEqual(missingHookLines(preCommit, ""), [
      CHECK_COMMIT_LINE,
      BIOME_LINE,
    ]);
  });

  it("does not count a commented-out line or another subcommand", () => {
    assert.deepEqual(
      missingHookLines(
        preCommit,
        `# ${CHECK_COMMIT_LINE}\n  # ${BIOME_LINE}\n`,
      ),
      [CHECK_COMMIT_LINE, BIOME_LINE],
    );
    assert.deepEqual(
      missingHookLines(
        preCommit,
        `${CHECK_PUSH_LINE}\nnode_modules/.bin/biome lint\n`,
      ),
      [CHECK_COMMIT_LINE, BIOME_LINE],
    );
  });
});

describe("isPinnedSpec", () => {
  const pinned = [
    "0.0.7",
    "1.2.3",
    "1.2.3-beta.1",
    "1.2.3+build.5",
    "git+https://github.com/acme/style-guide.git#0123abc",
    "git+ssh://git@github.com/acme/style-guide.git",
    "git://github.com/acme/style-guide.git",
    "github:acme/style-guide#v1.2.3",
    "acme/style-guide",
    "acme/style-guide#0123abc",
  ];
  for (const spec of pinned) {
    it(`takes ${spec}`, () => {
      assert.equal(isPinnedSpec(spec), true);
    });
  }

  const loose = [
    "^1.2.3",
    "~1.2.3",
    "1.2",
    "1.x",
    "*",
    "",
    "latest",
    ">=1.0.0",
    "workspace:*",
    "catalog:",
  ];
  const local = [
    "file:../style-guide",
    "./style-guide",
    "../style-guide/pkg",
    "https://example.com/style-guide.tgz",
  ];
  for (const spec of [...loose, ...local]) {
    it(`rejects ${JSON.stringify(spec)}`, () => {
      assert.equal(isPinnedSpec(spec), false);
    });
  }
});

describe("packageManualSteps", () => {
  it("is empty for husky, a prepare script that runs it, and an exact style-guide version", () => {
    assert.deepEqual(packageManualSteps(manifestText({})), []);
    assert.deepEqual(
      packageManualSteps(
        manifestText({ scripts: { prepare: "husky || true" } }),
      ),
      [],
    );
  });

  it("reports husky missing from devDependencies, also when it is only in dependencies", () => {
    const devDependencies = { "@pleand-inc/style-guide": "1.2.3" };
    const steps = packageManualSteps(
      manifestText({ devDependencies, dependencies: { husky: "9.1.7" } }),
    );
    assert.deepEqual(steps, ["package.json: add husky to devDependencies"]);
  });

  it("reports a missing prepare script and one that does not run husky", () => {
    const expected = [
      'package.json: add a prepare script that runs husky ("prepare": "husky")',
    ];
    assert.deepEqual(
      packageManualSteps(manifestText({ scripts: {} })),
      expected,
    );
    assert.deepEqual(
      packageManualSteps(manifestText({ scripts: undefined })),
      expected,
    );
    assert.deepEqual(
      packageManualSteps(
        manifestText({ scripts: { prepare: "npm run build" } }),
      ),
      expected,
    );
    assert.deepEqual(
      packageManualSteps(manifestText({ scripts: { prepare: "huskyish" } })),
      expected,
    );
  });

  it("reports a style-guide version that is a range, showing what it found", () => {
    const devDependencies = {
      "@pleand-inc/style-guide": "^1.2.3",
      husky: "9.1.7",
    };
    assert.deepEqual(packageManualSteps(manifestText({ devDependencies })), [
      "package.json: pin @pleand-inc/style-guide in devDependencies to an exact version or a git spec " +
        '(found "^1.2.3")',
    ]);
  });

  it("reports style-guide missing from devDependencies, which is where the workflows read it", () => {
    const steps = packageManualSteps(
      manifestText({ devDependencies: { husky: "9.1.7" } }),
    );
    assert.deepEqual(steps, [
      "package.json: add @pleand-inc/style-guide to devDependencies at an exact version",
    ]);
  });

  it("reports all three for an empty manifest", () => {
    assert.equal(packageManualSteps("{}").length, 3);
  });

  it("reports a missing or unreadable package.json as one step", () => {
    const expected = [
      "package.json: add a package.json that holds a JSON object",
    ];
    assert.deepEqual(packageManualSteps(undefined), expected);
    assert.deepEqual(packageManualSteps("{ not json"), expected);
    assert.deepEqual(packageManualSteps("[]"), expected);
  });
});

describe("the setup inspection of an empty and of a set-up repository", () => {
  it("in an empty repository: init creates all five files and both commands list the manual steps", () => {
    const inspection = inspectSetup(new Map(), RULE_FILES);
    const plan = initPlan(inspection);
    assert.deepEqual(
      plan.writes.map((write) => write.path),
      [
        PULL_REQUEST_WORKFLOW_PATH,
        PUSH_WORKFLOW_PATH,
        SKILL_PATH,
        PRE_COMMIT_PATH,
        PRE_PUSH_PATH,
      ],
    );
    assert.equal(
      plan.writes[3].content,
      `${CHECK_COMMIT_LINE}\n${BIOME_LINE}\n`,
    );
    assert.equal(plan.writes[4].content, `${CHECK_PUSH_LINE}\n`);
    assert.deepEqual(plan.lines.slice(0, 5), [
      `created    ${PULL_REQUEST_WORKFLOW_PATH}`,
      `created    ${PUSH_WORKFLOW_PATH}`,
      `created    ${SKILL_PATH}`,
      `created    ${PRE_COMMIT_PATH}`,
      `created    ${PRE_PUSH_PATH}`,
    ]);
    assert.deepEqual(plan.lines.slice(5), [
      "manual: package.json: add a package.json that holds a JSON object",
      'manual: biome.json: extend the shared configuration ("extends": ["@pleand-inc/style-guide/biome"])',
    ]);
    assert.equal(plan.exitCode, 1);

    const report = checkReport(inspection);
    assert.deepEqual(report.lines, [
      `missing: ${PULL_REQUEST_WORKFLOW_PATH} (run style-guide init)`,
      `missing: ${PUSH_WORKFLOW_PATH} (run style-guide init)`,
      `missing: ${SKILL_PATH} (run style-guide init)`,
      `missing: ${PRE_COMMIT_PATH} (run style-guide init)`,
      `missing: ${PRE_PUSH_PATH} (run style-guide init)`,
      ...plan.lines.slice(5),
    ]);
    assert.equal(report.exitCode, 1);
  });

  it("in a set-up repository: init writes nothing, reports every file unchanged, and check passes", () => {
    const inspection = inspectSetup(completeRepositoryFiles(), RULE_FILES);
    const plan = initPlan(inspection);
    assert.deepEqual(plan.writes, []);
    assert.deepEqual(plan.lines, [
      `unchanged  ${PULL_REQUEST_WORKFLOW_PATH}`,
      `unchanged  ${PUSH_WORKFLOW_PATH}`,
      `unchanged  ${SKILL_PATH}`,
      `unchanged  ${PRE_COMMIT_PATH}`,
      `unchanged  ${PRE_PUSH_PATH}`,
    ]);
    assert.equal(plan.exitCode, 0);
    assert.deepEqual(checkReport(inspection), {
      lines: ["style-guide check: the setup is current"],
      exitCode: 0,
    });
  });
});

describe("the setup inspection of the owned files", () => {
  it("an edited owned file: check names it and init rewrites it", () => {
    const files = completeRepositoryFiles();
    files.set(
      PUSH_WORKFLOW_PATH,
      contentOf(PUSH_WORKFLOW_PATH).replace(
        "timeout-minutes: 5",
        "timeout-minutes: 30",
      ),
    );
    const inspection = inspectSetup(files, RULE_FILES);
    assert.deepEqual(checkReport(inspection), {
      lines: [`differs: ${PUSH_WORKFLOW_PATH} (run style-guide init)`],
      exitCode: 1,
    });
    const plan = initPlan(inspection);
    assert.deepEqual(plan.writes, [
      { path: PUSH_WORKFLOW_PATH, content: contentOf(PUSH_WORKFLOW_PATH) },
    ]);
    assert.equal(plan.lines[1], `rewritten  ${PUSH_WORKFLOW_PATH}`);
    assert.equal(plan.exitCode, 0);
  });

  it("a skill generated from another set of rule files differs", () => {
    const inspection = inspectSetup(completeRepositoryFiles(), ["RULES.md"]);
    assert.deepEqual(checkReport(inspection).lines, [
      `differs: ${SKILL_PATH} (run style-guide init)`,
    ]);
  });

  it("an owned file checked out with CRLF line endings is current", () => {
    const files = completeRepositoryFiles();
    for (const { path, content } of ownedFiles(RULE_FILES))
      files.set(path, content.replaceAll("\n", "\r\n"));
    assert.equal(checkReport(inspectSetup(files, RULE_FILES)).exitCode, 0);
  });
});

describe("the setup inspection of the hooks", () => {
  it("an existing hook without a required line: init leaves it alone and prints the line to add", () => {
    const files = completeRepositoryFiles();
    files.set(PRE_COMMIT_PATH, "npm test\n");
    files.set(PRE_PUSH_PATH, "# nothing yet\n");
    const inspection = inspectSetup(files, RULE_FILES);
    const plan = initPlan(inspection);
    assert.deepEqual(plan.writes, []);
    assert.deepEqual(plan.lines.slice(3), [
      `incomplete ${PRE_COMMIT_PATH}`,
      `incomplete ${PRE_PUSH_PATH}`,
      `manual: add this line to ${PRE_COMMIT_PATH}: ${CHECK_COMMIT_LINE}`,
      `manual: add this line to ${PRE_COMMIT_PATH}: ${BIOME_LINE}`,
      `manual: add this line to ${PRE_PUSH_PATH}: ${CHECK_PUSH_LINE}`,
    ]);
    assert.equal(plan.exitCode, 1);
    assert.deepEqual(checkReport(inspection), {
      lines: plan.lines.slice(5),
      exitCode: 1,
    });
  });

  it("a deleted hook: check names it and init creates it again", () => {
    const files = completeRepositoryFiles();
    files.delete(PRE_PUSH_PATH);
    const inspection = inspectSetup(files, RULE_FILES);
    assert.deepEqual(checkReport(inspection), {
      lines: [`missing: ${PRE_PUSH_PATH} (run style-guide init)`],
      exitCode: 1,
    });
    assert.deepEqual(initPlan(inspection).writes, [
      { path: PRE_PUSH_PATH, content: `${CHECK_PUSH_LINE}\n` },
    ]);
  });
});

describe("the setup inspection of what init never writes", () => {
  it("the Biome configuration: either file name counts, and it must name the shared configuration", () => {
    const expected = [
      'manual: biome.json: extend the shared configuration ("extends": ["@pleand-inc/style-guide/biome"])',
    ];
    const jsonc = completeRepositoryFiles();
    jsonc.set("biome.jsonc", jsonc.get("biome.json"));
    jsonc.delete("biome.json");
    assert.equal(checkReport(inspectSetup(jsonc, RULE_FILES)).exitCode, 0);

    const own = completeRepositoryFiles();
    own.set("biome.json", '{ "linter": { "enabled": true } }');
    assert.deepEqual(
      checkReport(inspectSetup(own, RULE_FILES)).lines,
      expected,
    );

    const none = completeRepositoryFiles();
    none.delete("biome.json");
    assert.deepEqual(
      checkReport(inspectSetup(none, RULE_FILES)).lines,
      expected,
    );
    assert.equal(initPlan(inspectSetup(none, RULE_FILES)).exitCode, 1);
  });

  it("package.json steps are listed by both commands and are never written", () => {
    const files = completeRepositoryFiles();
    files.set(
      "package.json",
      manifestText({
        devDependencies: { "@pleand-inc/style-guide": "^1.2.3" },
      }),
    );
    const inspection = inspectSetup(files, RULE_FILES);
    const plan = initPlan(inspection);
    assert.deepEqual(plan.writes, []);
    assert.equal(plan.exitCode, 1);
    assert.deepEqual(checkReport(inspection).lines, plan.lines.slice(5));
    assert.equal(checkReport(inspection).lines.length, 2);
  });
});
